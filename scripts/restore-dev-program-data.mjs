/**
 * Restore program-module rows captured by the migration backup.
 *
 * Patient links are rebuilt by medical record number because the migration
 * recreates every patient row with a new id. Rows whose patient is no longer
 * present are skipped and reported rather than inserted with a broken link.
 *
 * Usage:
 *   node scripts/restore-dev-program-data.mjs [backupFileName]
 */

import fs from 'fs';
import path from 'path';
import { createClient } from '@supabase/supabase-js';

function readEnv(envFileName) {
  const envPath = path.resolve(process.cwd(), envFileName);
  if (!fs.existsSync(envPath)) return {};

  const env = {};
  fs.readFileSync(envPath, 'utf-8')
    .split('\n')
    .forEach((line) => {
      const trimmed = line.trim();
      if (trimmed && !trimmed.startsWith('#')) {
        const [key, ...values] = trimmed.split('=');
        env[key.trim()] = values.join('=').trim();
      }
    });
  return env;
}

function projectRef(url) {
  const match = /https:\/\/([^.]+)\./.exec(url || '');
  return match ? match[1] : null;
}

const env = readEnv('.env.local');
const prodEnv = readEnv('.env.production');

const SUPABASE_URL = env.NEXT_PUBLIC_SUPABASE_URL;
const SERVICE_ROLE_KEY = env.SUPABASE_SERVICE_ROLE_KEY;

if (!SUPABASE_URL || !SERVICE_ROLE_KEY) {
  console.error('Kredensial Supabase tidak ditemukan di .env.local');
  process.exit(1);
}

const targetRef = projectRef(SUPABASE_URL);
const prodRef = projectRef(prodEnv.NEXT_PUBLIC_SUPABASE_URL);

if (prodRef && targetRef === prodRef) {
  console.error('DIHENTIKAN: target kredensial menunjuk ke project produksi.');
  process.exit(1);
}

const supabase = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
});

const PROGRAM_TABLES = ['tbc_programs', 'circumcisions', 'post_cares'];

function resolveBackupPath() {
  const backupDir = path.resolve(process.cwd(), 'docs/data');
  const explicit = process.argv[2];

  if (explicit) return path.join(backupDir, explicit);

  const candidates = fs
    .readdirSync(backupDir)
    .filter((name) => name.startsWith('dev-program-backup-'))
    .sort()
    .reverse();

  if (candidates.length === 0) return null;
  return path.join(backupDir, candidates[0]);
}

async function fetchPatientIdMap() {
  const map = new Map();
  const pageSize = 1000;
  let page = 0;

  while (true) {
    const { data, error } = await supabase
      .from('patients')
      .select('id, no_rm')
      .range(page * pageSize, (page + 1) * pageSize - 1);
    if (error) throw new Error(`Gagal membaca pasien: ${error.message}`);
    if (!data || data.length === 0) break;

    data.forEach((row) => map.set(row.no_rm, row.id));
    if (data.length < pageSize) break;
    page += 1;
  }
  return map;
}

async function restore() {
  const backupPath = resolveBackupPath();
  if (!backupPath || !fs.existsSync(backupPath)) {
    console.error('Berkas backup data program tidak ditemukan di docs/data.');
    process.exit(1);
  }

  const backup = JSON.parse(fs.readFileSync(backupPath, 'utf-8'));
  console.log(`Target project (dev): ${targetRef}`);
  console.log(`Berkas backup       : ${path.basename(backupPath)}`);
  console.log(`Dibuat              : ${backup.createdAt}`);

  const patientIdByNoRm = await fetchPatientIdMap();

  let restored = 0;
  let skipped = 0;

  for (const table of PROGRAM_TABLES) {
    const rows = backup.tables[table] || [];
    if (rows.length === 0) continue;

    const prepared = [];

    for (const row of rows) {
      const { __pasien_no_rm: noRm, visit_id: _visitId, id: _id, created_at: _createdAt, ...rest } = row;

      const patientId = noRm ? patientIdByNoRm.get(noRm) : null;
      if (noRm && !patientId) {
        skipped += 1;
        console.log(`  Dilewati 1 baris ${table}: pasien ${noRm} tidak ada di data baru.`);
        continue;
      }

      prepared.push({
        ...rest,
        pasien_id: patientId,
        // Visit ids are regenerated by the migration, so the old link is dropped.
        ...('visit_id' in row ? { visit_id: null } : {}),
      });
    }

    if (prepared.length === 0) continue;

    const { error } = await supabase.from(table).insert(prepared);
    if (error) throw new Error(`Gagal memulihkan ${table}: ${error.message}`);

    restored += prepared.length;
    console.log(`  Dipulihkan ${prepared.length} baris ke ${table}.`);
  }

  console.log('\n======================================================');
  console.log(`Restore selesai: ${restored} baris dipulihkan, ${skipped} dilewati.`);
  console.log('======================================================\n');
}

restore().catch((error) => {
  console.error('Restore gagal:', error.message);
  process.exit(1);
});
